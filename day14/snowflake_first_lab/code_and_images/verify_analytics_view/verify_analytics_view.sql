-- Verify the view before creating dashboards

-- Verify Analytics View
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDERS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS
FROM RETAIL_LAB_DB.ANALYTICS.V_RETAIL_SALES;

-- Verify Business METRICS

SELECT
    ROUND(SUM(REALIZED_REVENUE), 2)
        AS TOTAL_DELIVERED_REVENUE,

    COUNT_IF(ORDER_STATUS = 'DELIVERED')
        AS TOTAL_DELIVERED_ORDERS,

    COUNT(DISTINCT
        IFF(ORDER_STATUS = 'DELIVERED',
            CUSTOMER_ID,
            NULL))
        AS TOTAL_DELIVERED_CUSTOMERS,

    ROUND(
        SUM(REALIZED_REVENUE) /
        NULLIF(COUNT_IF(ORDER_STATUS = 'DELIVERED'), 0),
        2
    ) AS AVERAGE_ORDER_VALUE

FROM RETAIL_LAB_DB.ANALYTICS.V_RETAIL_SALES;

-- Verify missing value handling
SELECT
    CLEAN_CITY,
    COUNT(*) AS TOTAL_ORDERS
FROM RETAIL_LAB_DB.ANALYTICS.V_RETAIL_SALES
WHERE CLEAN_CITY = 'Unknown'
GROUP BY CLEAN_CITY;