CREATE TABLE IF NOT EXISTS RETAIL_LAB_DB.RAW.RETAIL_ORDERS (
  ORDER_ID VARCHAR(20),
  ORDER_DATE DATE,
  CUSTOMER_ID VARCHAR(12),
  CUSTOMER_NAME VARCHAR(100),
  PRODUCT_ID VARCHAR(12),
  PRODUCT VARCHAR(100),
  CATEGORY VARCHAR(50),
  QUANTITY NUMBER(10,0),
  UNIT_PRICE NUMBER(12,2),
  DISCOUNT_PCT NUMBER(5,2),
  CITY VARCHAR(100),
  STATE VARCHAR(80),
  PAYMENT_METHOD VARCHAR(30),
  SALES_CHANNEL VARCHAR(30),
  ORDER_STATUS VARCHAR(30),
  SHIPPING_FEE NUMBER(10,2),
  CUSTOMER_SEGMENT VARCHAR(20)
);
DESCRIBE TABLE RETAIL_LAB_DB.RAW.RETAIL_ORDERS;
SHOW TABLES LIKE 'RETAIL_ORDERS' IN SCHEMA RETAIL_LAB_DB.RAW;

CREATE FILE FORMAT IF NOT EXISTS RETAIL_LAB_DB.RAW.RETAIL_CSV_FORMAT
  TYPE = CSV
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  DATE_FORMAT = 'YYYY-MM-DD'
  COMPRESSION = AUTO;
SHOW FILE FORMATS IN SCHEMA RETAIL_LAB_DB.RAW;
