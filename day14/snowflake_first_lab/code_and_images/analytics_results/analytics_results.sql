CREATE OR REPLACE VIEW RETAIL_LAB_DB.ANALYTICS.V_RETAIL_SALES AS
SELECT ORDER_ID, ORDER_DATE, CUSTOMER_ID, CUSTOMER_NAME,
       PRODUCT_ID, PRODUCT, CATEGORY, QUANTITY, UNIT_PRICE,
       COALESCE(DISCOUNT_PCT, 0) AS DISCOUNT_PCT,
       CASE
          WHEN CITY IS NULL OR TRIM(CITY) = '' THEN 'Unknown'
          WHEN UPPER(TRIM(CITY)) IN ('BANGALORE','BENGALURU') THEN 'Bengaluru'
          WHEN UPPER(TRIM(CITY)) IN ('COCHIN','KOCHI') THEN 'Kochi'
          ELSE INITCAP(TRIM(CITY))
       END AS CLEAN_CITY,
       STATE, PAYMENT_METHOD, SALES_CHANNEL, ORDER_STATUS,
       SHIPPING_FEE, CUSTOMER_SEGMENT,
       ROUND(QUANTITY * UNIT_PRICE, 2) AS GROSS_AMOUNT,
       ROUND(QUANTITY * UNIT_PRICE *
             (1 - COALESCE(DISCOUNT_PCT,0)/100), 2) AS NET_ITEM_AMOUNT,
       IFF(ORDER_STATUS = 'DELIVERED',
           ROUND(QUANTITY * UNIT_PRICE *
                 (1 - COALESCE(DISCOUNT_PCT,0)/100), 2),
           0) AS REALIZED_REVENUE
FROM RETAIL_LAB_DB.RAW.RETAIL_ORDERS;

SELECT * FROM RETAIL_LAB_DB.ANALYTICS.V_RETAIL_SALES LIMIT 10;
