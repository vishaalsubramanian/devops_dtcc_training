COPY INTO RETAIL_LAB_DB.RAW.RETAIL_ORDERS
  FROM @RETAIL_LAB_DB.RAW.RETAIL_STAGE
  FILES = ('retail_orders_2026.csv')
  FILE_FORMAT = (FORMAT_NAME = 'RETAIL_LAB_DB.RAW.RETAIL_CSV_FORMAT')
  ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_ROWS,
       COUNT(DISTINCT ORDER_ID) AS DISTINCT_ORDERS,
       COUNT(DISTINCT CUSTOMER_ID) AS DISTINCT_CUSTOMERS,
       MIN(ORDER_DATE) AS EARLIEST_ORDER,
       MAX(ORDER_DATE) AS LATEST_ORDER
FROM RETAIL_LAB_DB.RAW.RETAIL_ORDERS;
-- Expected TOTAL_ROWS 540, DISTINCT_ORDERS 540, DISTINCT_CUSTOMERS 120.

SELECT * FROM RETAIL_LAB_DB.RAW.RETAIL_ORDERS
ORDER BY ORDER_DATE DESC, ORDER_ID DESC LIMIT 10;

SELECT ORDER_STATUS, COUNT(*) AS ORDERS
FROM RETAIL_LAB_DB.RAW.RETAIL_ORDERS
GROUP BY ORDER_STATUS
ORDER BY ORDERS DESC;

SELECT ORDER_ID, COUNT(*) AS DUPLICATE_COUNT
FROM RETAIL_LAB_DB.RAW.RETAIL_ORDERS
GROUP BY ORDER_ID HAVING COUNT(*) > 1;
-- Expected 0 rows.

SELECT COUNT_IF(CITY IS NULL) AS MISSING_CITY,
       COUNT_IF(DISCOUNT_PCT IS NULL) AS MISSING_DISCOUNT,
       COUNT_IF(QUANTITY <= 0) AS NONPOSITIVE_QTY,
       COUNT_IF(UNIT_PRICE < 0) AS NEGATIVE_PRICE
FROM RETAIL_LAB_DB.RAW.RETAIL_ORDERS;
-- Expected: 7 missing city, 6 missing discount; no nonpositive quantities or negative prices.

SELECT FILE_NAME, STATUS, ROW_COUNT, ROW_PARSED, LAST_LOAD_TIME
FROM RETAIL_LAB_DB.INFORMATION_SCHEMA.LOAD_HISTORY
WHERE SCHEMA_NAME = 'RAW'
  AND TABLE_NAME = 'RETAIL_ORDERS'
ORDER BY LAST_LOAD_TIME DESC;
