CREATE WAREHOUSE IF NOT EXISTS RETAIL_LAB_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
       AUTO_SUSPEND = 60
       AUTO_RESUME = TRUE
       INITIALLY_SUSPENDED = TRUE
       MIN_CLUSTER_COUNT = 1
       MAX_CLUSTER_COUNT = 1;

-- Ensure safe settings even if warehouse already existed.
ALTER WAREHOUSE RETAIL_LAB_WH
  SET WAREHOUSE_SIZE = 'XSMALL'
      AUTO_SUSPEND = 60
      AUTO_RESUME = TRUE;
USE WAREHOUSE RETAIL_LAB_WH;
SHOW WAREHOUSES LIKE 'RETAIL_LAB_WH';
SELECT CURRENT_WAREHOUSE();
